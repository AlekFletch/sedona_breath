// Generates the shared parts of the lite-wearable (Watch Fit) build from the ArkTS app,
// so both versions have a single source of truth:
//
//  1. entry/src/main/ets/core/*.ets  ->  lite/.../MainAbility/core/*.js   (ES5, ES modules)
//  2. entry/src/main/resources/{base,en,es}/element/string.json
//                                    ->  lite/.../MainAbility/i18n/<page>.js (one dictionary per page)
//     Only keys used by the lite sources are included (lite JS heap is small).
//  3. Checks that no lite .js uses RegExp (not available on the watch).
//
// Usage:
//   node tools/build-lite.mjs           regenerate
//   node tools/build-lite.mjs --check   fail (exit 1) if generated files are out of date
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const check = process.argv.includes('--check');

const tsCandidates = [
  process.env.TS_PATH,
  'C:/Program Files/Huawei/DevEco Studio/sdk/default/openharmony/ets/build-tools/ets-loader/node_modules/typescript',
  '/Applications/DevEco-Studio.app/Contents/sdk/default/openharmony/ets/build-tools/ets-loader/node_modules/typescript',
  'typescript'
].filter(Boolean);
let ts;
for (const c of tsCandidates) {
  try { ts = require(c); break; } catch { /* try next */ }
}
if (!ts) { console.error('TypeScript not found: set TS_PATH'); process.exit(2); }

const coreSrc = path.join(root, 'entry/src/main/ets/core');
const liteJs = path.join(root, 'lite/entry/src/main/js/MainAbility');
const HEADER = '// GENERATED by tools/build-lite.mjs from entry/src/main/ets/core — do not edit.\n';
const outputs = new Map();

// 1. Core
for (const f of fs.readdirSync(coreSrc).filter((n) => n.endsWith('.ets')).sort()) {
  const src = fs.readFileSync(path.join(coreSrc, f), 'utf8');
  let js = ts.transpileModule(src, {
    compilerOptions: {
      module: ts.ModuleKind.ES2015, target: ts.ScriptTarget.ES5, removeComments: false,
      newLine: ts.NewLineKind.LineFeed
    }
  }).outputText;
  js = js.replace(/from '\.\/(\w+)'/g, "from './$1.js'");
  outputs.set(path.join(liteJs, 'core', f.replace(/\.ets$/, '.js')), HEADER + js);
}

// 2. Strings live outside the JS bundles, in the lite runtime's own i18n files read by $t():
//    i18n/{en-US,ru-RU,es-ES}.json are identical and hold all three languages ({ ru: {...}, en: ..., es: ... }),
//    so the language can be chosen in Settings: store.t() calls $t('<lang>.<key>'). The JS heap
//    (~100 KB, half of it the framework) then holds only the strings a page shows.
//    Every key a page can show is collected: s.key in its .hml, quoted keys in its .js and in
//    the common/*.js modules it imports; a quoted prefix such as 'pattern_' (store.label('pattern_', id))
//    brings every key starting with it. i18n/<page>.js lists the .hml keys, which store.strings() fills.
const baseKeys = new Set(JSON.parse(fs.readFileSync(path.join(root, 'entry/src/main/resources/base/element/string.json'),
  'utf8')).string.map((e) => e.name));
const sortedKeys = [...baseKeys].sort();
const quotedKeys = (src) => [...src.matchAll(/'([a-z][A-Za-z0-9_]*)'/g)].map((m) => m[1]).flatMap((q) => {
  if (baseKeys.has(q)) return [q];
  return q.endsWith('_') ? sortedKeys.filter((k) => k.startsWith(q)) : [];
});
const read = (p) => fs.readFileSync(p, 'utf8');
/** The page script and the common/*.js modules it imports, transitively (core/ has no strings). */
const scriptsOf = (file, seen = new Set()) => {
  if (seen.has(file)) return seen;
  seen.add(file);
  for (const m of read(file).matchAll(/from '(\.[^']+\.js)'/g)) {
    const dep = path.resolve(path.dirname(file), m[1]);
    if (dep.startsWith(path.join(liteJs, 'common'))) scriptsOf(dep, seen);
  }
  return seen;
};
const pages = {};
const templateKeys = {};
for (const page of fs.readdirSync(path.join(liteJs, 'pages')).sort()) {
  const dir = path.join(liteJs, 'pages', page);
  const keys = new Set([...read(path.join(dir, `${page}.hml`)).matchAll(/\bs\.([A-Za-z0-9_]+)/g)].map((m) => m[1]));
  templateKeys[page] = [...keys].sort();
  for (const f of scriptsOf(path.join(dir, `${page}.js`))) for (const k of quotedKeys(read(f))) keys.add(k);
  pages[page] = [...keys];
}
const LANGS = { ru: 'base', en: 'en', es: 'es' };
const tables = Object.fromEntries(Object.entries(LANGS).map(([lang, dir]) => [lang, new Map(JSON.parse(
  read(path.join(root, 'entry/src/main/resources', dir, 'element/string.json'))).string.map((e) => [e.name, e.value]))]));
const missing = Object.values(pages).flat().filter((k) => !tables.ru.has(k));
if (missing.length) {
  console.error(`Lite sources reference unknown string keys: ${[...new Set(missing)].join(', ')}`);
  process.exit(1);
}
const used = new Set(Object.values(pages).flat());
const dict = Object.fromEntries(Object.keys(LANGS).map((lang) =>
  [lang, Object.fromEntries([...used].sort().map((k) => [k, tables[lang].get(k)]))]));
// The runtime picks the file by system locale and falls back to en-US; each holds every language.
for (const locale of ['en-US', 'ru-RU', 'es-ES']) {
  outputs.set(path.join(liteJs, `i18n/${locale}.json`), `${JSON.stringify(dict, null, 1)}\n`);
}
for (const [page, keys] of Object.entries(templateKeys)) {
  outputs.set(path.join(liteJs, `i18n/${page}.js`),
    '// GENERATED by tools/build-lite.mjs from pages/' + page + '/' + page + '.hml — do not edit.\n' +
    `// String keys of the template (s.key); the texts are in i18n/*.json.\n` +
    `export default ${JSON.stringify(keys)};\n`);
}

let stale = 0;
for (const [file, content] of outputs) {
  const old = fs.existsSync(file) ? fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n') : null;
  if (old === content) continue;
  stale++;
  if (check) {
    console.log(`out of date: ${path.relative(root, file)}`);
  } else {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, content);
    console.log(`wrote ${path.relative(root, file)}`);
  }
}
if (check && stale) {
  console.log('\nRun: node tools/build-lite.mjs');
  process.exitCode = 1;
} else {
  console.log(`${outputs.size} generated files, ${stale} ${check ? 'stale' : 'updated'}; ${used.size} string keys`);
}

// 3. The watch's JS engine is built without RegExp: the installer compiles every .js to
// bytecode on the watch and rejects the whole HAP with error 34 if one file fails.
const regexUses = [];
const scanJs = (dir) => {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) { scanJs(p); continue; }
    if (!e.name.endsWith('.js')) continue;
    const text = outputs.get(p) ?? fs.readFileSync(p, 'utf8');
    const sf = ts.createSourceFile(p, text, ts.ScriptTarget.ES5, true, ts.ScriptKind.JS);
    const visit = (n) => {
      if (n.kind === ts.SyntaxKind.RegularExpressionLiteral || (ts.isIdentifier(n) && n.text === 'RegExp')) {
        regexUses.push(`${path.relative(root, p)}:${sf.getLineAndCharacterOfPosition(n.getStart()).line + 1}`);
      }
      ts.forEachChild(n, visit);
    };
    visit(sf);
  }
};
scanJs(liteJs);
if (regexUses.length) {
  console.log(`RegExp is not available on the watch (install error 34):\n  ${regexUses.join('\n  ')}`);
  process.exitCode = 1;
}
